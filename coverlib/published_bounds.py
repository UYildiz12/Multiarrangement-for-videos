def published_lower_bound(v: int, k: int) -> Optional[Tuple[int, str]]:
    """The largest imported lower bound on C(v, k, 2) and its source, or None when none is listed."""
    best = None
    for table, source in ((LJCR_LOWER_BOUNDS, LJCR_SOURCE), (THIS_WORK_LOWER_BOUNDS, THIS_WORK_SOURCE)):
        value = table.get((int(v), int(k)))
        if value is not None and (best is None or value > best[0]):
            best = (value, source)
    return best
